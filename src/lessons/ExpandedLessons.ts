export function buildExpandedLessons(baseLessons: LessonDefinition[]): LessonDefinition[] {
  const byTopology = new Map<CircuitTopologyId, LessonDefinition>();
  for (const l of baseLessons) {
    byTopology.set(l.topology ?? (l.id as CircuitTopologyId), l);
  }

  return EXTRA_LESSON_SEEDS.map((seed, idx) => {
    const base = byTopology.get(seed.baseTopology) ?? baseLessons[0];
    const num = String(baseLessons.length + idx + 1).padStart(2, '0');
    return {
      id: seed.id,
      topology: seed.baseTopology,
      number: num,
      title: seed.title,
      shortTitle: seed.shortTitle,
      subtitle: seed.subtitle,
      category: seed.category,
      recommendedBoardId: seed.recommendedBoardId,
      difficulty: seed.difficulty,
      pinRole: base.pinRole,
      getPrimaryPin: (b: EspBoardId) => {
        const board = getEspBoardById(b);
        return base.getPrimaryPin(board.id);
      },
      summary: seed.summary,
      keyTakeaways: [...seed.keyTakeaways],
      formulas: [seed.formula, ...base.formulas.slice(0, 1)],
      challenges: [
        {
          id: `${seed.id}-ch1`,
          text: seed.challenge,
          hint: 'Nutze die Live-Regler rechts im Inspector oder klicke Bauteile direkt in 3D an.',
        },
        ...base.challenges.slice(0, 1),
      ],
      removableParts: base.removableParts,
      defaultParams: { ...base.defaultParams, ...seed.defaultParams },
      cameraPreset: base.cameraPreset,
    };
  });
}
