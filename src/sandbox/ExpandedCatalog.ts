import type { ExtraMeshStyle, ExtraSimKind, SandboxCatalogItem } from './SandboxTypes';

interface SensorSeed {
  type: string;
  name: string;
  shortName: string;
  simKind: 'i2c-sensor' | 'digital-sensor' | 'analog-sensor' | 'uart-sensor';
  meshStyle: Extract<
    ExtraMeshStyle,
    'sensor-pcb' | 'sensor-probe' | 'sensor-lens' | 'sensor-coil' | 'sensor-pad'
  >;
  badgeTitle: string;
  badgeSub: string;
  accentHex: string;
  currentMa: number;
  activeText: string;
  idleText: string;
  description: string;
}

interface ActuatorSeed {
  type: string;
  name: string;
  shortName: string;
  simKind: Extract<
    ExtraSimKind,
    'two-pin-actuator' | 'pwm-actuator' | 'i2c-display' | 'relay-actuator'
  >;
  meshStyle: Extract<
    ExtraMeshStyle,
    'actuator-motor' | 'actuator-display' | 'actuator-relay' | 'actuator-audio'
  >;
  badgeTitle: string;
  badgeSub: string;
  accentHex: string;
  currentMa: number;
  activeText: string;
  idleText: string;
  description: string;
}

function buildSensorItem(s: SensorSeed): SandboxCatalogItem {
  const isI2c = s.simKind === 'i2c-sensor';
  const isUart = s.simKind === 'uart-sensor';
  const pinOffsets = isI2c
    ? [
        { dCol: 0, row: 'f', pinLabel: '3V3' },
        { dCol: 1, row: 'f', pinLabel: 'GND' },
        { dCol: 2, row: 'f', pinLabel: 'SCL' },
        { dCol: 3, row: 'f', pinLabel: 'SDA' },
      ]
    : isUart
      ? [
          { dCol: 0, row: 'g', pinLabel: '3V3' },
          { dCol: 1, row: 'g', pinLabel: 'GND' },
          { dCol: 2, row: 'g', pinLabel: 'TX' },
          { dCol: 3, row: 'g', pinLabel: 'RX' },
        ]
      : [
          { dCol: 0, row: 'g', pinLabel: '3V3' },
          { dCol: 1, row: 'g', pinLabel: s.simKind === 'analog-sensor' ? 'AOUT' : 'OUT' },
          { dCol: 2, row: 'g', pinLabel: 'GND' },
        ];

  return {
    type: s.type,
    name: s.name,
    shortName: s.shortName,
    category: 'Sensoren',
    colSpan: pinOffsets.length - 1,
    preferredRow: isI2c ? 'f' : 'g',
    pinOffsets,
    description: s.description,
    accentHex: s.accentHex,
    extraMeta: {
      simKind: s.simKind,
      meshStyle: s.meshStyle,
      badgeTitle: s.badgeTitle,
      badgeSub: s.badgeSub,
      currentMa: s.currentMa,
      activeText: s.activeText,
      idleText: s.idleText,
    },
  };
}

function buildActuatorItem(a: ActuatorSeed): SandboxCatalogItem {
  const isI2c = a.simKind === 'i2c-display';
  const isTwoPin = a.simKind === 'two-pin-actuator';
  const pinOffsets = isI2c
    ? [
        { dCol: 0, row: 'f', pinLabel: 'GND' },
        { dCol: 1, row: 'f', pinLabel: '3V3' },
        { dCol: 2, row: 'f', pinLabel: 'SCL' },
        { dCol: 3, row: 'f', pinLabel: 'SDA' },
      ]
    : isTwoPin
      ? [
          { dCol: 0, row: 'g', pinLabel: '+V/SIG' },
          { dCol: 2, row: 'g', pinLabel: 'GND' },
        ]
      : [
          { dCol: 0, row: 'g', pinLabel: a.simKind === 'pwm-actuator' ? 'PWM/SIG' : 'IN' },
          { dCol: 1, row: 'g', pinLabel: '+V' },
          { dCol: 2, row: 'g', pinLabel: 'GND' },
        ];

  return {
    type: a.type,
    name: a.name,
    shortName: a.shortName,
    category: 'Aktoren & Displays',
    colSpan: isTwoPin ? 2 : pinOffsets.length - 1,
    preferredRow: isI2c ? 'f' : 'g',
    pinOffsets,
    description: a.description,
    accentHex: a.accentHex,
    extraMeta: {
      simKind: a.simKind,
      meshStyle: a.meshStyle,
      badgeTitle: a.badgeTitle,
      badgeSub: a.badgeSub,
      currentMa: a.currentMa,
      activeText: a.activeText,
      idleText: a.idleText,
    },
  };
}

