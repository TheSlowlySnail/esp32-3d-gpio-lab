export function getEspBoardById(id: EspBoardId): EspBoardSpec {
  return ESP_BOARDS.find((b) => b.id === id) ?? ESP_BOARDS[0];
}

export function isRaspberryPiSbc(id: EspBoardId): boolean {
  return getEspBoardById(id).family === 'raspberry-pi-sbc';
}

export function isRaspberryPiAny(id: EspBoardId): boolean {
  const f = getEspBoardById(id).family;
  return f === 'raspberry-pi-sbc' || f === 'raspberry-pi-mcu';
}

export function isArduinoBoard(id: EspBoardId): boolean {
  return getEspBoardById(id).family === 'arduino';
}
